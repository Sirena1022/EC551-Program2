
import argparse
import json
import re
from collections import defaultdict
from pathlib import Path

UNITS = {'+': ('adder', 'adders'), '-': ('subtractor', 'subtractors'), '*': ('multiplier', 'multipliers')}
IDENT = re.compile(r'^[A-Za-z_][A-Za-z_0-9]*$')

def generate(data, width=16, module='generated_circuit'):
    if not 1 <= width <= 32:
        raise ValueError('Width must be 1..32')
    if not IDENT.fullmatch(module):
        raise ValueError('Invalid module name')
    ops = data['operations']
    if not ops:
        raise ValueError('Schedule has no operations')
    inputs = data['inputs']
    finals = data['final_versions']
    targets = [op['target'] for op in ops]
    if len(set(targets)) != len(targets):
        raise ValueError('SSA targets must be unique')
    if len(set(inputs)) != len(inputs) or set(inputs) & set(targets):
        raise ValueError('Inputs must be unique and disjoint from targets')
    for name in inputs + targets + list(finals):
        if not IDENT.fullmatch(name):
            raise ValueError(f'Invalid identifier: {name}')
    by_cycle = defaultdict(list)
    for op in ops:
        t = op['cycle']
        if not isinstance(t, int) or t < 1 or op['operator'] not in UNITS:
            raise ValueError('Invalid cycle or operator')
        by_cycle[t].append(op)
    latency = data['latency_cycles']
    if not isinstance(latency, int) or latency < max(by_cycle):
        raise ValueError('Invalid latency')
    producer = {op['target']: op for op in ops}
    for op in ops:
        for operand in (op['left'], op['right']):
            if operand.isdecimal():
                if int(operand) >= 2**width:
                    raise ValueError(f'Constant {operand} does not fit {width} bits')
            elif operand in producer:
                if producer[operand]['cycle'] >= op['cycle']:
                    raise ValueError(f'Dependency not ready for {op["target"]}')
            elif operand not in inputs:
                raise ValueError(f'Unknown operand {operand}')
    for name, version in finals.items():
        if version not in producer:
            raise ValueError(f'Unknown final version {version}')
    # Maximum simultaneous operations of each type = minimum units for this schedule.
    counts = {kind: max((sum(UNITS[op['operator']][1] == kind for op in by_cycle[t]) for t in range(1, latency+1)), default=0) for _,kind in UNITS.values()}
    slots = defaultdict(list)
    assignments = {}
    for t in range(1, latency+1):
        used = defaultdict(int)
        for op in sorted(by_cycle[t], key=lambda x: x['id']):
            typ,kind = UNITS[op['operator']]
            index = used[kind]
            used[kind] += 1
            assignments[op['target']] = (kind, index)
            slots[(kind,index)].append(op)
    ports = ['input wire clk', 'input wire reset', 'input wire start']
    ports += [f'input wire [{width-1}:0] {n}' for n in inputs]
    ports += ['output reg done']
    ports += [f'output wire [{width-1}:0] out_{n}' for n in finals]
    # Explicit observability ports for selecting each physical functional unit.
    ports += ['input wire [7:0] observe_index', 'input wire [1:0] observe_type', f'output reg [{width-1}:0] observe_data']
    lines = ['`timescale 1ns / 1ps', '// Generated by EC551 Python HLS tool; one-cycle arithmetic operations.', f'module {module} (', '    ' + ',\n    '.join(ports), ');', '']
    state_width = max(1, (latency + 2).bit_length())
    lines += [f'  reg [{state_width-1}:0] state;', f'  localparam [{state_width-1}:0] IDLE = 0, DONE = {latency+1};']
    for t in range(1, latency+1):
        lines.append(f'  localparam [{state_width-1}:0] CYCLE_{t} = {t};')
    lines += ['', '  // Intermediate registers hold results across scheduled cycles.']
    for target in targets:
        lines.append(f'  reg [{width-1}:0] reg_{target};')
    lines += ['']
    def value(x):
        if x.isdecimal():
            return f"{width}'d{x}"
        return f'reg_{x}' if x in producer else x
    # Every unit gets a MUX-controlled pair of inputs and a combinational output.
    for (kind,index), slotops in sorted(slots.items()):
        typ = next(t for t,k in UNITS.values() if k == kind)
        tag = f'{typ}_{index}'
        lines += [f'  reg [{width-1}:0] {tag}_a, {tag}_b;', f'  wire [{width-1}:0] {tag}_result;', f'  {typ} #(.WIDTH({width})) u_{tag} (.a({tag}_a), .b({tag}_b), .result({tag}_result));', '  always @(*) begin', f"    {tag}_a = {width}'d0;", f"    {tag}_b = {width}'d0;", '    case (state)']
        for op in slotops:
            lines += [f"      CYCLE_{op['cycle']}: begin", f"        {tag}_a = {value(op['left'])};", f"        {tag}_b = {value(op['right'])};", '      end']
        lines += ['      default: begin end', '    endcase', '  end', '']
    # FSM controls register writes and state transitions.
    lines += ['  always @(posedge clk) begin', '    if (reset) begin', '      state <= IDLE;', "      done <= 1'b0;"]
    for target in targets:
        lines.append(f"      reg_{target} <= {width}'d0;")
    lines += ['    end else begin', '      case (state)', '        IDLE: begin', "          done <= 1'b0;", '          if (start) state <= CYCLE_1;', '        end']
    for t in range(1,latency+1):
        lines.append(f'        CYCLE_{t}: begin')
        for op in sorted(by_cycle[t], key=lambda x:x['id']):
            kind,index = assignments[op['target']]
            typ = next(n for n,k in UNITS.values() if k==kind)
            lines.append(f"          reg_{op['target']} <= {typ}_{index}_result;")
        lines.append(f'          state <= {"DONE" if t==latency else f"CYCLE_{t+1}"};')
        lines.append('        end')
    lines += ['        DONE: begin', "          done <= 1'b1;", '          if (!start) state <= IDLE;', '        end', '        default: state <= IDLE;', '      endcase', '    end', '  end', '']
    for name, version in finals.items():
        lines.append(f'  assign out_{name} = reg_{version};')
    lines += ['', '  // 00: adder, 01: subtractor, 10: multiplier.', '  always @(*) begin', f"    observe_data = {width}'d0;", '    case (observe_type)']
    for code,kind in [('00','adders'),('01','subtractors'),('10','multipliers')]:
        typ = next(n for n,k in UNITS.values() if k==kind)
        lines += [f"      2'b{code}: case (observe_index)"]
        for i in range(counts[kind]):
            lines.append(f"        8'd{i}: observe_data = {typ}_{i}_result;")
        lines += ['        default: begin end', '      endcase']
    lines += ['      default: begin end', '    endcase', '  end', 'endmodule', '']
    return '\n'.join(lines)

def main():
    p=argparse.ArgumentParser(description='Generate resource-shared Verilog from schedule.json')
    p.add_argument('schedule', nargs='?', default='schedule.json')
    p.add_argument('--output', default='generated.v')
    p.add_argument('--width', type=int, default=16)
    p.add_argument('--module', default='generated_circuit')
    args=p.parse_args()
    verilog=generate(json.loads(Path(args.schedule).read_text(encoding='utf-8')), args.width, args.module)
    Path(args.output).write_text(verilog, encoding='utf-8')
    print(f'Generated {args.output}')

if __name__ == '__main__':
    main()

